"""Hybrid dataset: IBM AML-Data (AMLworld) transactions + laundering labels, with PHANTOM's own
synthetic company / controller / address / invoice layers on top.

What comes from IBM (generated by IBM's multi-agent simulator, not by us):
    accounts, transfers, timestamps, amounts, the laundering flag, and (optionally) the pattern
    file that names each laundering attempt (FAN-OUT, CYCLE, ...).
What is OURS and synthetic:
    company attributes, ownership/directorship links (hidden controller shared by each laundering
    ring), shared addresses/phones, and one invoice per transfer. The invoice layer is
    label-neutral by design (same lag and item process for every account).

Sampling (important for honesty):
    * 'seed' accounts = all accounts of sampled laundering attempts + uniformly sampled benign
      accounts. Only seeds are scored, trained on and evaluated (`in_eval`).
    * 'fringe' accounts = counterparties of seeds; they give every seed its real neighbourhood
      so benign seeds are not artificially isolated. They are never evaluated.
    The induced graph is still far sparser than the full IBM graph, which can make rings easier to
    spot than on the full data. Treat results as optimistic.
"""
import re
from pathlib import Path
import numpy as np
import pandas as pd
from .config import GenConfig, SECTORS, SECTOR_LIST, SIZES, REGIONS
from .dataset import Dataset
from .generator import identity_layer
from .names import make_company_names

EXPECTED = ["timestamp", "from_bank", "from_account", "to_bank", "to_account",
            "amount_received", "amount_paid", "payment_format", "is_laundering"]


# --------------------------------------------------------------------------- schema detection
def detect_columns(columns):
    """Map the CSV header to canonical names. Handles the duplicated 'Account' header."""
    cols = list(columns)
    low = [str(c).strip().lower() for c in cols]
    m = {}

    def find(pred, key):
        for c, l in zip(cols, low):
            if pred(l) and c not in m.values():
                m[key] = c
                return

    find(lambda l: l == "timestamp" or "time" in l, "timestamp")
    find(lambda l: l == "from bank", "from_bank")
    find(lambda l: l == "to bank", "to_bank")
    acc = [c for c, l in zip(cols, low) if l.startswith("account")]
    if len(acc) >= 2:
        m["from_account"], m["to_account"] = acc[0], acc[1]
    find(lambda l: l == "amount received", "amount_received")
    find(lambda l: l == "amount paid", "amount_paid")
    find(lambda l: "payment format" in l or l == "payment type", "payment_format")
    find(lambda l: "laundering" in l, "is_laundering")
    missing = [k for k in EXPECTED if k not in m]
    if missing:
        raise ValueError(f"Could not identify columns {missing}. Header found: {cols}. "
                         "Send this header and I will adapt the loader.")
    return m


def _read_header(path):
    return list(pd.read_csv(path, nrows=0).columns)


def _chunks(path, cm, chunksize):
    use = [cm[k] for k in EXPECTED]
    for ch in pd.read_csv(path, usecols=use, chunksize=chunksize, dtype=str):
        ch = ch.rename(columns={v: k for k, v in cm.items()})
        ch["src"] = ch.from_bank.str.strip() + "_" + ch.from_account.str.strip()
        ch["dst"] = ch.to_bank.str.strip() + "_" + ch.to_account.str.strip()
        ch["amount"] = pd.to_numeric(ch.amount_received, errors="coerce").fillna(0.0)
        ch["laundering"] = pd.to_numeric(ch.is_laundering, errors="coerce").fillna(0).astype(int)
        yield ch


# --------------------------------------------------------------------------- patterns file
def parse_patterns(path):
    """List of {type, accounts:set} from the pattern file (BEGIN/END LAUNDERING ATTEMPT blocks)."""
    attempts, cur = [], None
    for line in Path(path).read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        m = re.match(r"BEGIN LAUNDERING ATTEMPT\s*-?\s*(.*)", line, re.I)
        if m:
            # real headers carry parameters ("CYCLE:  Max 2 hops"); keep only the family name
            family = re.split(r"[:\s]", m.group(1).strip(), maxsplit=1)[0].lower()
            cur = dict(type=family or "unknown", accounts=set())
            continue
        if re.match(r"END LAUNDERING ATTEMPT", line, re.I):
            if cur and cur["accounts"]:
                attempts.append(cur)
            cur = None
            continue
        if cur is not None and "," in line:
            f = line.split(",")
            if len(f) >= 5:
                cur["accounts"].add(f"{f[1].strip()}_{f[2].strip()}")
                cur["accounts"].add(f"{f[3].strip()}_{f[4].strip()}")
    return attempts


# --------------------------------------------------------------------------- inspection
def inspect_aml(trans, patterns=None, chunksize=1_000_000):
    cols = _read_header(trans)
    cm = detect_columns(cols)
    rows = laund = 0
    accts = set()
    tmin = tmax = None
    for ch in _chunks(trans, cm, chunksize):
        rows += len(ch)
        laund += int(ch.laundering.sum())
        accts.update(ch.src.unique()); accts.update(ch.dst.unique())
        ts = pd.to_datetime(ch.timestamp, errors="coerce")
        tmin = ts.min() if tmin is None else min(tmin, ts.min())
        tmax = ts.max() if tmax is None else max(tmax, ts.max())
    out = dict(header=cols, detected=cm, rows=rows, laundering_rows=laund,
               laundering_rate=laund / max(rows, 1), accounts=len(accts), time_range=(str(tmin), str(tmax)))
    if patterns:
        att = parse_patterns(patterns)
        out["pattern_attempts"] = len(att)
        out["pattern_types"] = pd.Series([a["type"] for a in att]).value_counts().to_dict()
        out["pattern_accounts_median"] = float(np.median([len(a["accounts"]) for a in att])) if att else 0
    return out


# --------------------------------------------------------------------------- ring structure
def _ring_groups(laund_df, attempts):
    """Merge overlapping attempts into ring groups. Returns list of dict(accounts:set, type:str)."""
    if attempts:
        items = [(a["accounts"], a["type"]) for a in attempts]
    else:   # no pattern file: connected components of laundering transfers
        items = [({s, d}, "unknown") for s, d in zip(laund_df.src, laund_df.dst)]
    parent = {}

    def find(x):
        while parent.setdefault(x, x) != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    for accs, _ in items:
        accs = list(accs)
        for a in accs[1:]:
            parent[find(a)] = find(accs[0])
    groups = {}
    for accs, typ in items:
        r = find(next(iter(accs)))
        g = groups.setdefault(r, dict(accounts=set(), types=set()))
        g["accounts"] |= accs
        g["types"].add(typ)
    return [dict(accounts=g["accounts"], type="+".join(sorted(g["types"]))) for g in groups.values()]


# --------------------------------------------------------------------------- build
def build_dataset(trans, patterns=None, n_benign_seeds=3000, ring_fraction=0.025, max_ring_accounts=60,
                  min_benign_degree=2, seed=42, controller_obs_rate=0.5, benign_group_fraction=0.05,
                  max_nodes=80_000, chunksize=1_000_000, log=print) -> Dataset:
    rng = np.random.default_rng(seed)
    cm = detect_columns(_read_header(trans))

    log("pass 1/3: degrees, laundering transfers, time range")
    deg, laund_parts, tmin = None, [], None
    for ch in _chunks(trans, cm, chunksize):
        d = pd.concat([ch.src, ch.dst]).value_counts()
        deg = d if deg is None else deg.add(d, fill_value=0)
        laund_parts.append(ch[ch.laundering == 1][["src", "dst"]])
        ts = pd.to_datetime(ch.timestamp, errors="coerce").min()
        tmin = ts if tmin is None else min(tmin, ts)
    laund = pd.concat(laund_parts, ignore_index=True)
    L = set(laund.src) | set(laund.dst)
    attempts = parse_patterns(patterns) if patterns else []
    groups = [g for g in _ring_groups(laund, attempts) if 2 <= len(g["accounts"]) <= max_ring_accounts]
    log(f"  accounts={len(deg):,}  laundering accounts={len(L):,}  usable ring groups={len(groups)}")
    if not groups:
        raise ValueError("No usable laundering groups found (check the patterns file / Is Laundering column).")

    # choose ring groups until the target prevalence is met
    target = int(round(ring_fraction / (1 - ring_fraction) * n_benign_seeds))
    order = rng.permutation(len(groups))
    chosen, used = [], 0
    for i in order:
        if used >= target:
            break
        chosen.append(groups[i])
        used += len(groups[i]["accounts"])
    ring_accounts = set().union(*[g["accounts"] for g in chosen])
    pool = deg[(deg >= min_benign_degree) & (~deg.index.isin(L))].index
    benign_seeds = set(rng.choice(pool.to_numpy(), min(n_benign_seeds, len(pool)), replace=False))
    seeds = ring_accounts | benign_seeds
    log(f"  seeds: {len(ring_accounts)} ring accounts in {len(chosen)} groups + {len(benign_seeds)} benign")

    log("pass 2/3: fringe (counterparties of seeds)")
    fringe = set()
    for ch in _chunks(trans, cm, chunksize):
        a = ch[ch.src.isin(seeds) | ch.dst.isin(seeds)]
        fringe |= set(a.src) | set(a.dst)
    fringe -= seeds
    if len(seeds) + len(fringe) > max_nodes:
        keep = rng.choice(sorted(fringe), max(0, max_nodes - len(seeds)), replace=False)
        log(f"  fringe capped from {len(fringe):,} to {len(keep):,}")
        fringe = set(keep)
    nodes = seeds | fringe

    log("pass 3/3: transfers among selected accounts")
    parts = []
    for ch in _chunks(trans, cm, chunksize):
        parts.append(ch[ch.src.isin(nodes) & ch.dst.isin(nodes) & (ch.src != ch.dst)])
    tx = pd.concat(parts, ignore_index=True)
    tx["ts"] = pd.to_datetime(tx.timestamp, errors="coerce")
    tx = tx.dropna(subset=["ts"])
    tx["t"] = (tx.ts - tmin).dt.total_seconds() / 86400.0
    horizon = int(np.ceil(tx.t.max())) + 1
    tx["day"] = np.floor(tx.t).astype(int)
    log(f"  nodes={len(nodes):,} transfers={len(tx):,} horizon={horizon} days")

    # ---- companies (one per account)
    accts = sorted(nodes)
    n = len(accts)
    cid = np.array([f"C{i:06d}" for i in range(n)])
    idx = {a: i for i, a in enumerate(accts)}
    vol = pd.concat([tx.groupby("src").amount.sum(), tx.groupby("dst").amount.sum()]).groupby(level=0).sum()
    vq = pd.Series(vol).reindex(accts).fillna(0).rank(pct=True).to_numpy()
    size = np.where(vq < 0.55, "small", np.where(vq < 0.88, "medium", "large")).astype(object)
    flip = rng.random(n) < 0.25                                   # declared size only loosely tracks volume
    size[flip] = rng.choice(SIZES, flip.sum())
    sector = rng.choice(SECTOR_LIST, n)
    region = rng.choice(REGIONS, n)
    reg_day = -rng.integers(30, 365 * 15, n)
    young = rng.random(n) < 0.10
    reg_day[young] = -rng.integers(30, 365, n)[young]

    # ---- ring / benign group structure for the identity layer
    rings = []
    for k, g in enumerate(chosen):
        rings.append(dict(id=f"R{k:03d}", members=np.array(sorted(idx[a] for a in g["accounts"])),
                          typology=g["type"], seed=int(rng.integers(0, 2**31 - 1))))
    taken = {int(i) for r in rings for i in r["members"]}
    free = [idx[a] for a in sorted(benign_seeds) if idx[a] not in taken]
    free = list(rng.permutation(free))
    groups_b, gi, cursor = [], 0, 0
    while gi < int(benign_group_fraction * len(free)) and cursor + 4 <= len(free):
        k = int(rng.integers(2, 5))
        groups_b.append(dict(id=f"G{len(groups_b):03d}", members=np.array(free[cursor:cursor + k])))
        cursor += k
        gi += k
    cowork = []
    for s in range(8):
        k = int(rng.integers(15, 36))
        if cursor + k > len(free):
            break
        cowork.append(dict(id=f"W{s:03d}", members=np.array(free[cursor:cursor + k])))
        cursor += k
    ring_of = {int(i): r for r in rings for i in r["members"]}
    group_of = {int(i): g["id"] for g in groups_b for i in g["members"]}
    for w in cowork:
        for i in w["members"]:
            group_of[int(i)] = w["id"]
    for r in rings:                                               # same lifecycle tweak as the generator
        for i in r["members"]:
            if rng.random() < 0.4:
                reg_day[i] = -rng.integers(60, 500)
    cfg = GenConfig(seed=seed, n_companies=n, horizon_days=horizon, controller_obs_rate=controller_obs_rate,
                    benign_group_fraction=benign_group_fraction)
    people, true_edges, rel, contacts, controller_of = identity_layer(
        rng, cfg, cid, region, reg_day, rings, groups_b, cowork, ring_of, group_of)

    # ---- accounts, transactions, invoices
    accounts = pd.DataFrame({"account_id": accts, "linked_entity_id": cid})
    tx = tx.reset_index(drop=True)
    tx_out = pd.DataFrame({
        "transaction_id": [f"TX{i:08d}" for i in range(len(tx))],
        "sender_account": tx.src, "receiver_account": tx.dst, "amount": tx.amount,
        "t": tx.t, "day": tx.day, "invoice_id": [f"INV{i:08d}" for i in range(len(tx))]})
    tx_out["timestamp"] = tx.ts.values
    issuer = tx.dst.map(lambda a: cid[idx[a]])           # the payee issued the invoice
    receiver = tx.src.map(lambda a: cid[idx[a]])
    sec_by_c = pd.Series(sector, index=cid)
    items = [rng.choice(SECTORS[s]) for s in sec_by_c.reindex(issuer).to_numpy()]
    wrong = rng.random(len(tx)) < 0.02                   # same noise rate for every account
    all_items = [it for v in SECTORS.values() for it in v]
    items = [rng.choice(all_items) if w else it for it, w in zip(items, wrong)]
    inv = pd.DataFrame({"invoice_id": tx_out.invoice_id, "issuer_id": issuer.values, "receiver_id": receiver.values,
                        "amount": tx.amount.values, "day": tx.day.values, "item_category": items})
    inv["issue_date"] = tmin + pd.to_timedelta(inv.day, unit="D")

    companies = pd.DataFrame({
        "company_id": cid, "name": make_company_names(seed, sector), "sector": sector, "declared_size": size,
        "registration_date": tmin + pd.to_timedelta(reg_day, unit="D"),
        "reg_day": reg_day, "region": region, "status": "active"})
    ring_label = {int(i): r for r in rings for i in r["members"]}
    lab = np.array([1 if a in L else 0 for a in accts])
    gt = pd.DataFrame({
        "entity_id": cid, "ring_id": [ring_label[i]["id"] if i in ring_label else None for i in range(n)],
        "controller_id": [controller_of[i] for i in range(n)],
        "typology": [ring_label[i]["typology"] if i in ring_label else "none" for i in range(n)],
        "injection_seed": [ring_label[i]["seed"] if i in ring_label else -1 for i in range(n)],
        "synthetic_label": lab, "archetype": "aml_account",
        "group_id": [group_of.get(i) for i in range(n)],
        "in_eval": [a in seeds for a in accts]})
    # laundering accounts that were NOT sampled as ring members stay label=1 but are never evaluated
    meta = dict(config=dict(cfg.to_dict(), horizon_days=horizon), source="IBM AML-Data + PHANTOM synthetic layers",
                feature_opts={"cycle_min_n": 1}, n_rings=len(rings),
                n_ring_members=int(gt[gt.in_eval].synthetic_label.sum()),
                prevalence=float(gt[gt.in_eval].synthetic_label.mean()),
                typology_counts=pd.Series([r["typology"] for r in rings]).value_counts().to_dict(),
                n_seeds=len(seeds), n_fringe=len(fringe), synthetic=True)
    return Dataset(companies, people, accounts, rel, contacts, inv, tx_out, gt, true_edges, meta)
